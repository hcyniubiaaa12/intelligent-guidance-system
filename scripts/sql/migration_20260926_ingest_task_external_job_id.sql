-- ============================================================
-- 增量迁移：ingest_task 增加 external_job_id（外部解析服务任务号）
-- 背景：链路 B 上传流水线的解析走外部服务（阿里云 DocumentMind），它是**提交 + 轮询**的
--       异步形态，解析一份件可能要几分钟。编排因此拆成两段：
--         ① 线程池只负责「提交」，拿到外部任务号就结束，不占着线程等；
--         ② @Scheduled 定时扫 status=running 且 stage=parse 的任务去轮询，
--            完成后才投回线程池做「读结果 → 切分 → 入库」。
--       第 ② 段要能**在进程重启后接着轮询**——靠的就是本列。
-- 语义：这个值**推不出来**（丢了就真的接不上外部任务），与「向量表要不要存 task_id」
--       那个被否掉的冗余外键不是一回事。仅解析阶段有值，切分/向量化阶段为 NULL。
-- 影响：不执行时，新代码写这一列会报 Unknown column；上传流水线尚未动工，
--       当前不执行也不影响既有功能。
-- 执行：已在旧库上跑过 mysql_init.sql 的环境执行本脚本；全新初始化无需执行（脚本已含）。
-- ============================================================

ALTER TABLE `ingest_task`
    ADD COLUMN `external_job_id` VARCHAR(128) NULL
        COMMENT '外部解析服务（DocumentMind）的任务号；两段式编排靠它重启后接着轮询'
        AFTER `doc_id`;
